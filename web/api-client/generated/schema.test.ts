import { readFileSync } from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import type { paths } from './schema';

/**
 * F0-T04: generated types exist and cover the auth surface the client needs.
 * Full CI drift gate comes later; this guards accidental empty/broken generation.
 */
describe('generated OpenAPI types (F0-T04)', () => {
  it('exports path keys for auth and session surfaces', () => {
    // Type-level: assigning ensures the keys exist on `paths`
    const required = [
      '/v1/auth/login',
      '/v1/auth/refresh',
      '/v1/auth/logout',
      '/v1/me',
      '/v1/timelines/home',
    ] as const satisfies ReadonlyArray<keyof paths>;

    expect(required.length).toBe(5);
  });

  it('schema.ts is non-empty generated output', () => {
    const file = path.join(__dirname, 'schema.ts');
    const src = readFileSync(file, 'utf8');
    expect(src).toContain('This file was auto-generated by openapi-typescript');
    expect(src).toContain('export interface paths');
    expect(src.length).toBeGreaterThan(1000);
  });
});
